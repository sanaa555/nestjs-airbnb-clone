


import { applyDecorators } from '@nestjs/common';
import {
  ApiBody,
  ApiHeader,
  ApiOperation,
  ApiResponse,
} from '@nestjs/swagger';

function errorResponseSchema(example: string) {
  return {
    type: 'object',
    required: ['errors'],
    properties: {
      errors: {
        type: 'array',
        items: {
          type: 'object',
          required: ['message'],
          properties: {
            message: {
              type: 'string',
              example,
            },
          },
        },
      },
    },
  };
}

export function HandleWebhookSwagger() {
  return applyDecorators(
    ApiOperation({
      summary: 'Handle Stripe webhook events',
      description:
        'Receive a Stripe event and process it after validating the Stripe-Signature against the raw request body. Swagger UI cannot generate a valid Stripe signature; use Stripe CLI or a real Stripe webhook for testing.',
    }),
    ApiHeader({
      name: 'Stripe-Signature',
      description: 'Signature generated by Stripe for the raw webhook request body.',
      required: true,
      schema: { type: 'string' },
    }),
    ApiBody({
      description: 'Raw Stripe event payload. The signature must match these exact bytes.',
      schema: {
        type: 'object',
        additionalProperties: true,
        example: {
          id: 'evt_123456789',
          object: 'event',
          type: 'checkout.session.completed',
          data: { object: { id: 'cs_test_123456789' } },
        },
      },
    }),
    ApiResponse({
      status: 200,
      description: 'The Stripe event was received and processed.',
      schema: {
        type: 'object',
        required: ['received'],
        properties: { received: { type: 'boolean', example: true } },
      },
    }),
    ApiResponse({
      status: 400,
      description: 'The raw request body or Stripe signature is missing or invalid.',
      schema: errorResponseSchema('Invalid Stripe webhook request'),
    }),
  );
}